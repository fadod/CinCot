    /// <summary>Brings a window to the foreground even when another process owns focus.</summary>
    public static void ForceForeground(IntPtr hwnd)
    {
        var foreground = GetForegroundWindow();
        uint foregroundThread = GetWindowThreadProcessId(foreground, out _);
        uint thisThread = GetCurrentThreadId();
        if (foregroundThread != thisThread && foregroundThread != 0)
        {
            AttachThreadInput(thisThread, foregroundThread, true);
            SetForegroundWindow(hwnd);
            AttachThreadInput(thisThread, foregroundThread, false);
        }
        else
        {
            SetForegroundWindow(hwnd);
        }
    }

    /// <summary>Effective DPI scale (1.0 = 96 DPI) of the monitor containing a physical-pixel point.</summary>
    public static float ScaleAt(Point screenPoint)
    {
        var monitor = MonitorFromPoint(screenPoint, MONITOR_DEFAULTTONEAREST);
        return GetDpiForMonitor(monitor, 0, out uint dpi, out _) == 0 ? dpi / 96f : 1f;
    }
